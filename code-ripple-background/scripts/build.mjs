import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

mkdirSync('src/generated', { recursive: true });

function b64(name) {
  return readFileSync(`assets/${name}.b64`, 'utf8').trim();
}

const assets = `// Generated by scripts/build.mjs from assets/*.b64 - do not edit by hand.
export const MAID_MASK_SRC = 'data:image/jpeg;base64,${b64('maid')}';
export const CHIBI_MASK_SRC = 'data:image/jpeg;base64,${b64('chibi')}';
export const EARTH_MASK_SRC = 'data:image/png;base64,${b64('earth')}';
export const SHANNON_ZH_MASK_SRC = 'data:image/jpeg;base64,${b64('shannon-zh')}';
export const SHANNON_MASK_SRC = 'data:image/jpeg;base64,${b64('shannon')}';
export const NEUMANN_ZH_MASK_SRC = 'data:image/jpeg;base64,${b64('neumann-zh')}';
export const NEUMANN_MASK_SRC = 'data:image/jpeg;base64,${b64('neumann')}';
export const TURING_ZH_MASK_SRC = 'data:image/jpeg;base64,${b64('turing-zh')}';
export const TURING_MASK_SRC = 'data:image/jpeg;base64,${b64('turing')}';
export const LOGO_PATH = ${JSON.stringify(readFileSync('assets/logo-path.txt', 'utf8').trim())};
`;
mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/assets.ts', assets);

await build({
  entryPoints: ['src/client.ts'],
  bundle: true,
  format: 'iife',
  target: 'es2022',
  platform: 'browser',
  outfile: 'client.js',
  legalComments: 'none',
});

await build({
  entryPoints: ['src/host.ts'],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  platform: 'neutral',
  outfile: 'index.js',
  legalComments: 'none',
});

console.log('built client.js and index.js');
